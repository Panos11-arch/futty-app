const unit = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;

/** 6 -> "6 ώρες", 1 -> "1 ώρα". */
export function hoursTextEl(n: number): string {
  return unit(n, 'ώρα', 'ώρες');
}

/** 15 -> "15 λεπτά"; whole hours read as hours: 60 -> "1 ώρα". */
export function minutesTextEl(n: number): string {
  return n > 0 && n % 60 === 0 ? hoursTextEl(n / 60) : unit(n, 'λεπτό', 'λεπτά');
}

/** 7 -> "7 ημέρες", 1 -> "1 ημέρα". */
export function daysTextEl(n: number): string {
  return unit(n, 'ημέρα', 'ημέρες');
}

/** 12 -> "12 μήνες", 1 -> "1 μήνα". */
export function monthsTextEl(n: number): string {
  return unit(n, 'μήνα', 'μήνες');
}

/** 72 -> "3 ημέρες", 6 -> "6 ώρες". */
function hoursOrDaysEl(hours: number): string {
  return hours > 0 && hours % 24 === 0 ? daysTextEl(hours / 24) : hoursTextEl(hours);
}

function premiumOwnSpotEl(r: AppRules): string {
  return r.fee_premium_cents === 0
    ? 'δεν πληρώνουν χρέωση υπηρεσίας για τη δική τους θέση'
    : `πληρώνουν χρέωση υπηρεσίας ${eurosText(r.fee_premium_cents)} για τη δική τους θέση`;
}

