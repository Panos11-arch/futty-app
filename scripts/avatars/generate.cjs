/* global __dirname */
// S18: makes assets/avatars/illustrations.ts, the bundled illustrated avatars.
// Run once, from a temp folder that has DiceBear installed (it is never a
// dependency of the app, so package.json does not change):
//
//   cd <temp> && npm i @dicebear/core@9 @dicebear/collection@9
//   NODE_PATH=<temp>/node_modules node scripts/avatars/generate.cjs
//
// The art is Avataaars by Pablo Stanley, "Free for personal and commercial
// use" (https://avataaars.com/); see assets/avatars/LICENSE.md. Only friendly
// options are used (no crying, dizzy or eye-roll eyes, no sad, scream or
// vomit mouths, no printed shirts, no eyepatch or sunglasses).
//
// The ids live in lib/avatar-illustrations.ts and are stored on the server;
// this file only decides the drawings, so the set can be redrawn later
// without changing an id.
const fs = require('node:fs');
const path = require('node:path');
const { createAvatar } = require('@dicebear/core');
const { avataaars } = require('@dicebear/collection');

const COUNT = 48;
const ids = Array.from({ length: COUNT }, (_, i) => `avatar-${String(i + 1).padStart(2, '0')}`);

const options = {
  size: 96,
  eyes: ['default', 'happy', 'side', 'squint', 'wink'],
  mouth: ['default', 'smile', 'twinkle'],
  eyebrows: ['default', 'defaultNatural', 'raisedExcited', 'raisedExcitedNatural', 'flatNatural', 'upDown'],
  clothing: [
    'blazerAndShirt',
    'blazerAndSweater',
    'collarAndSweater',
    'hoodie',
    'overall',
    'shirtCrewNeck',
    'shirtScoopNeck',
    'shirtVNeck',
  ],
  skinColor: ['614335', 'ae5d29', 'd08b5b', 'edb98a', 'ffdbb4'],
  accessories: ['prescription01', 'prescription02', 'round', 'wayfarers'],
  accessoriesProbability: 15,
  facialHairProbability: 15,
};

function minify(svg) {
  return svg
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
    .replace(/>\s+</g, '><')
    .trim();
}

const drawings = ids.map((id) => [id, minify(createAvatar(avataaars, { ...options, seed: `futty-${id}` }).toString())]);

const out = [
  '// Generated by scripts/avatars/generate.cjs. Do not edit by hand.',
  '// Avataaars by Pablo Stanley, free for personal and commercial use',
  '// (https://avataaars.com/), via DiceBear (MIT). See assets/avatars/LICENSE.md.',
  "import type { AvatarIllustrationId } from '@/lib/avatar-illustrations';",
  '',
  'export const ILLUSTRATION_SVGS: Record<AvatarIllustrationId, string> = {',
  ...drawings.map(([id, svg]) => `  '${id}': ${JSON.stringify(svg)},`),
  '};',
  '',
].join('\n');

const file = path.join(__dirname, '..', '..', 'assets', 'avatars', 'illustrations.ts');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out);
console.log(`Wrote ${ids.length} avatars, ${Math.round(out.length / 1024)} KB, to ${file}`);
